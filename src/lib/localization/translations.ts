const translationLookup = new Map<string, Translation>();

for (const translation of translationEntries) {
  translationLookup.set(translation.ko, translation);
  translationLookup.set(translation.en, translation);
  translationLookup.set(normalizeTranslationKey(translation.en), translation);
}

translationLookup.set('account delete', { en: 'Delete account', ko: '계정 삭제' });

export function translateText(language: AppLanguage, text: string): string {
  const leadingWhitespace = text.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = text.match(/\s*$/)?.[0] ?? '';
  const normalizedText = text.trim();
  if (!normalizedText) return text;
  const translation = translationLookup.get(normalizedText) ?? translationLookup.get(normalizeTranslationKey(normalizedText));
  return translation ? `${leadingWhitespace}${translation[language]}${trailingWhitespace}` : text;
}

function normalizeTranslationKey(text: string): string {
  return text.toLowerCase().replaceAll("'", '’');
}

function entry(ko: string, en: string): Translation {
  return { en, ko };
}
